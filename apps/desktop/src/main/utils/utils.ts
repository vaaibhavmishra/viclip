import type { ClipContentType } from "@viclip/types";
import { shell } from "electron";
import log from "electron-log/main";

const SAFE_PROTOCOLS = new Set(["https:", "http:", "mailto:"]);

/**
 * Validates that a URL uses an approved protocol (https, http, mailto)
 * before invoking OS shell.openExternal, preventing arbitrary execution
 * or abuse of dangerous protocol schemes (file:, javascript:, applescript:, etc).
 */
export function openSafeExternal(rawUrl: string): boolean {
  try {
    if (typeof rawUrl !== "string" || rawUrl.length > 8192) return false;
    const parsed = new URL(rawUrl);
    if (SAFE_PROTOCOLS.has(parsed.protocol)) {
      shell.openExternal(parsed.href).catch(() => {
        log.error("Failed to open external URL");
      });
      return true;
    }
    log.warn(
      `Blocked attempt to open untrusted or dangerous URL scheme: ${parsed.protocol}`,
    );
    return false;
  } catch {
    log.warn("Blocked invalid URL string");
    return false;
  }
}

/**
 * Checks whether the clipboard format list contains privacy or concealment markers
 * set by password managers (1Password, Bitwarden, KeePass, macOS Keychain).
 */
export function isConcealedClipboard(formats: string[]): boolean {
  const sensitiveFormats = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
    "Clipboard Viewer Ignore",
    "ExcludeClipboardContentFromMonitorProcessing",
  ];
  return formats.some((f) => sensitiveFormats.includes(f));
}

export function detectClipboardType(
  text: string,
  formats: string[],
): ClipContentType {
  const trimmed = text.trim();
  if (trimmed.length === 0 && formats.length === 0) return "unknown";

  // 1. Formatted text detection
  if (formats.includes("text/html") || formats.includes("text/rtf")) {
    return "text-formatted";
  }

  // 2. File/URI-list detection (by extension)
  if (formats.includes("text/uri-list")) {
    const lower = trimmed.toLowerCase();
    const ext = lower.substring(lower.lastIndexOf("."));

    const docExts = [".doc", ".docx", ".pdf", ".txt", ".rtf", ".odt", ".pages"];
    if (docExts.includes(ext)) return "document";

    const spreadsheetExts = [".xls", ".xlsx", ".csv", ".numbers"];
    if (spreadsheetExts.includes(ext)) return "spreadsheet";

    const presentationExts = [".ppt", ".pptx", ".key"];
    if (presentationExts.includes(ext)) return "presentation";

    // If it's a URL in uri-list
    if (/^https?:\/\//i.test(trimmed)) return "url";
  }

  // 4. URL detection (plain text)
  if (/^https?:\/\//i.test(trimmed)) {
    return "url";
  }

  // 5. Email detection
  if (/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(trimmed)) {
    return "email";
  }

  // 6. Color code detection (hex, rgb/rgba, hsl/hsla)
  if (
    /^#([0-9A-Fa-f]{3,8})$/.test(trimmed) ||
    /^rgba?\(\s*\d{1,3}\s*,\s*\d{1,3}\s*,\s*\d{1,3}(\s*,\s*(0|1|0?\.\d+|100%|\d{1,2}%))?\s*\)$/i.test(
      trimmed,
    ) ||
    /^hsla?\(\s*\d{1,3}\s*,\s*(\d{1,3}%\s*,\s*){2}(0|1|0?\.\d+|100%|\d{1,2}%)\s*\)$/i.test(
      trimmed,
    )
  ) {
    return "color";
  }

  // 7. Plain text fallback
  if (trimmed.length > 0) {
    return "text";
  }

  return "unknown";
}
